# 8. Pooled panel (Driscoll-Kraay): one row per spec
# -------------------------------------------------------------
pull_dk <- function(res, label, term) {
  ct <- res$coeftest
  if (!(term %in% rownames(ct))) {
    return(tibble(spec = label, term = term,
                  estimate = NA, se = NA, t = NA, p = NA))
  }
  tibble(
    spec     = label,
    term     = term,
    estimate = ct[term, "Estimate"],
    se       = ct[term, "Std. Error"],
    t        = ct[term, "t value"],
    p        = ct[term, "Pr(>|t|)"]
  )
}
panel_tbl <- bind_rows(
  pull_dk(panel_18, "Eq (18): rx $\\sim$ CF",            "CF"),
  pull_dk(panel_19, "Eq (19): rx $\\sim$ CF + GCF",      "CF"),
  pull_dk(panel_19, "Eq (19): rx $\\sim$ CF + GCF",      "GCF"),
  pull_dk(panel_20, "Eq (20): rx $\\sim$ GCF",           "GCF"),
  pull_dk(panel_21, "Eq (21): rx$^{USD}\\sim$ CF + GCF", "CF"),
  pull_dk(panel_21, "Eq (21): rx$^{USD}\\sim$ CF + GCF", "GCF"),
  pull_dk(panel_22, "Eq (22): rx$^{USD}\\sim$ GCF",      "GCF"),
  pull_dk(panel_23, "Eq (23): rx$^{USD}\\sim$ FXGCF",    "FXGCF")
)

panel_rows <- panel_tbl %>%
  transmute(
    Specification = spec,
    Term          = term,
    Estimate      = paste0(fmt_num(estimate, 3), star(p)),
    `DK SE`       = fmt_num(se, 3),
    `$t$`         = fmt_num(t, 2)
  )
write_tabular(
  rows   = as.matrix(panel_rows),
  header = colnames(panel_rows),
  align  = "llrrr",
  file   = "panel_dk.tex"
)


# 3. LaTeX-table helpers (no kableExtra dependency)
# -------------------------------------------------------------
fmt_num <- function(x, digits = 3) {
  ifelse(is.na(x), "--", formatC(x, format = "f", digits = digits))
}
fmt_pct <- function(x, digits = 1) {
  ifelse(is.na(x), "--", paste0(formatC(100 * x, format = "f", digits = digits), "\\%"))
}
fmt_int <- function(x) ifelse(is.na(x), "--", formatC(x, format = "d", big.mark = ","))
star <- function(p) {
  ifelse(is.na(p), "",
  ifelse(p < 0.01, "$^{***}$",
  ifelse(p < 0.05, "$^{**}$",
  ifelse(p < 0.10, "$^{*}$", ""))))
}

# Build a booktabs tabular (no caption / float -- wrap in beamer)
write_tabular <- function(rows, header, align, file) {
  body <- vapply(seq_len(nrow(rows)),
                 function(i) paste0(paste(rows[i, ], collapse = " & "), " \\\\"),
                 character(1))
  lines <- c(
    "% auto-generated by presentation_output.R; do not edit",
    sprintf("\\begin{tabular}{%s}", align),
    "\\toprule",
    paste0(paste(header, collapse = " & "), " \\\\"),
    "\\midrule",
    body,
    "\\bottomrule",
    "\\end{tabular}"
  )
  writeLines(lines, file.path(TAB_DIR, file))
}

